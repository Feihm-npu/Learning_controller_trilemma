#!/usr/bin/env python3
"""Generate the TDSC core-results table directly from locked CSV artifacts."""

from __future__ import annotations

import argparse
import csv
from dataclasses import asdict, dataclass
from pathlib import Path


ROOT = Path(__file__).resolve().parent
RESULTS = ROOT / "results"


@dataclass(frozen=True)
class ResultRow:
    system: str
    mechanism: str
    learner_seeds: int
    rollouts: int
    violations: int
    mean_reward: float
    source_file: str


@dataclass(frozen=True)
class CoverageTableRow:
    mechanism: str
    evaluated_pairs: int
    pybullet_violations: int
    certified_pairs: int
    false_acceptances: int
    false_rejections: int
    certificate_coverage: float
    source_file: str


def read_rows(path: Path) -> list[dict[str, str]]:
    with path.open(newline="") as source:
        return list(csv.DictReader(source))


def by_mechanism(path: Path) -> dict[str, dict[str, str]]:
    rows = read_rows(path)
    return {row["mechanism"]: row for row in rows}


def locked_rows() -> list[ResultRow]:
    cart_path = RESULTS / "safe_control_gym_reinforce_reward_poisoning_aggregate.csv"
    quad_path = (
        RESULTS
        / "safe_control_gym_quadrotor_reinforce_reward_poisoning_aggregate.csv"
    )
    cart = by_mechanism(cart_path)
    quad = by_mechanism(quad_path)

    rows: list[ResultRow] = []
    specifications = (
        (
            "Cartpole",
            cart_path,
            cart,
            "clean_reinforce_snapshot",
            "Clean REINFORCE",
            "admitted_rollouts",
        ),
        (
            "Cartpole",
            cart_path,
            cart,
            "poisoned_action_only_snapshot",
            "Poisoned action-only",
            "admitted_rollouts",
        ),
        (
            "Cartpole",
            cart_path,
            cart,
            "poisoned_commit_gate_snapshot",
            "Poisoned commit",
            "admitted_rollouts",
        ),
        (
            "Cartpole",
            cart_path,
            cart,
            "poisoned_always_freeze_snapshot",
            "Always-freeze",
            "admitted_rollouts",
        ),
        (
            "Quadrotor",
            quad_path,
            quad,
            "clean_reinforce_snapshot",
            "Clean REINFORCE",
            "deployment_rollouts",
        ),
        (
            "Quadrotor",
            quad_path,
            quad,
            "poisoned_action_only_snapshot",
            "Poisoned action-only",
            "deployment_rollouts",
        ),
        (
            "Quadrotor",
            quad_path,
            quad,
            "poisoned_commit_gate_snapshot",
            "Poisoned commit",
            "deployment_rollouts",
        ),
        (
            "Quadrotor",
            quad_path,
            quad,
            "poisoned_always_freeze_snapshot",
            "Always-freeze",
            "deployment_rollouts",
        ),
    )
    for system, path, lookup, key, display, rollout_field in specifications:
        if key not in lookup:
            raise RuntimeError(f"{path.name}: missing mechanism {key}")
        row = lookup[key]
        seed_field = (
            "learner_seeds" if "learner_seeds" in row else "policy_seeds"
        )
        reward_field = (
            "mean_reward"
            if "mean_reward" in row
            else "mean_deployment_reward"
        )
        if reward_field not in row:
            raise RuntimeError(f"{path.name}: missing aggregate reward field")
        rows.append(
            ResultRow(
                system=system,
                mechanism=display,
                learner_seeds=int(row[seed_field]),
                rollouts=int(row[rollout_field]),
                violations=int(row["violating_rollouts"]),
                mean_reward=float(row[reward_field]),
                source_file=str(path.relative_to(ROOT)),
            )
        )

    return rows


def tex_rows(rows: list[ResultRow]) -> str:
    output = [
        "% Auto-generated by generate_tdsc_result_table.py; do not edit.",
        r"\begin{tabular}{llrrrr}",
        r"\toprule",
        (
            r"System & Mechanism & Learner seeds & Rollouts & Violations "
            r"& Mean reward \\"
        ),
        r"\midrule",
    ]
    previous_system: str | None = None
    for row in rows:
        if previous_system is not None and row.system != previous_system:
            output.append(r"\midrule")
        output.append(
            f"{row.system} & {row.mechanism} & {row.learner_seeds} & "
            f"{row.rollouts} & {row.violations} & "
            f"${row.mean_reward:.3f}$ \\\\"
        )
        previous_system = row.system
    output.extend([r"\bottomrule", r"\end{tabular}"])
    return "\n".join(output) + "\n"


def locked_coverage_rows() -> list[CoverageTableRow]:
    path = (
        RESULTS
        / "safe_control_gym_quadrotor_certificate_coverage_aggregate.csv"
    )
    rows = read_rows(path)
    selected = {
        row["mechanism"]: row
        for row in rows
        if row["learner_seed"] == "pooled"
        and int(row["horizon"]) == 100
        and float(row["guard_margin"]) == 0.003
    }
    display = {
        "clean_reinforce_snapshot": "Clean REINFORCE",
        "poisoned_action_only_snapshot": "Poisoned action-only",
        "poisoned_commit_gate_snapshot": "Poisoned commit",
        "poisoned_always_freeze_snapshot": "Always-freeze",
    }
    output: list[CoverageTableRow] = []
    for mechanism, label in display.items():
        if mechanism not in selected:
            raise RuntimeError(
                f"{path.name}: missing primary pooled row {mechanism}"
            )
        row = selected[mechanism]
        evaluated = int(row["evaluated_pairs"])
        output.append(
            CoverageTableRow(
                mechanism=label,
                evaluated_pairs=evaluated,
                pybullet_violations=(
                    evaluated - int(row["pybullet_safe_pairs"])
                ),
                certified_pairs=int(row["certified_pairs"]),
                false_acceptances=int(row["false_acceptances"]),
                false_rejections=int(row["false_rejections"]),
                certificate_coverage=float(row["certificate_coverage"]),
                source_file=str(path.relative_to(ROOT)),
            )
        )
    return output


def coverage_tex(rows: list[CoverageTableRow]) -> str:
    output = [
        "% Auto-generated by generate_tdsc_result_table.py; do not edit.",
        r"\begin{tabular}{lrrrrrr}",
        r"\toprule",
        (
            r"Snapshot & Pairs & Physical viol. & Certified & False accept "
            r"& False reject & Coverage \\"
        ),
        r"\midrule",
    ]
    for row in rows:
        output.append(
            f"{row.mechanism} & {row.evaluated_pairs} & "
            f"{row.pybullet_violations} & {row.certified_pairs} & "
            f"{row.false_acceptances} & {row.false_rejections} & "
            f"{row.certificate_coverage:.3f} \\\\"
        )
    output.extend([r"\bottomrule", r"\end{tabular}"])
    return "\n".join(output) + "\n"


def write_csv(path: Path, rows: list[object]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("w", newline="") as output:
        writer = csv.DictWriter(output, fieldnames=list(asdict(rows[0])))
        writer.writeheader()
        writer.writerows(asdict(row) for row in rows)


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--tex-out",
        type=Path,
        default=ROOT / "paper_latex" / "generated" / "tdsc_core_results.tex",
    )
    parser.add_argument(
        "--csv-out",
        type=Path,
        default=RESULTS / "tdsc_core_results.csv",
    )
    parser.add_argument(
        "--coverage-tex-out",
        type=Path,
        default=(
            ROOT
            / "paper_latex"
            / "generated"
            / "tdsc_coverage_results.tex"
        ),
    )
    parser.add_argument(
        "--coverage-csv-out",
        type=Path,
        default=RESULTS / "tdsc_coverage_results.csv",
    )
    return parser.parse_args()


def main() -> None:
    args = parse_args()
    rows = locked_rows()
    coverage_rows = locked_coverage_rows()
    args.tex_out.parent.mkdir(parents=True, exist_ok=True)
    args.tex_out.write_text(tex_rows(rows))
    write_csv(args.csv_out, rows)
    args.coverage_tex_out.parent.mkdir(parents=True, exist_ok=True)
    args.coverage_tex_out.write_text(coverage_tex(coverage_rows))
    write_csv(args.coverage_csv_out, coverage_rows)
    print(f"wrote {args.tex_out}")
    print(f"wrote {args.csv_out}")
    print(f"wrote {args.coverage_tex_out}")
    print(f"wrote {args.coverage_csv_out}")


if __name__ == "__main__":
    main()
